"""
The official books scripts/build_official.py adds to the library, and the list of every court in India
with its official website (data/laws/courts.json, shown on the Library -> Courts page).

A book is fetched from India Code (by title, or by its India Code id for Rules and State Acts) or from a
court website (url). Fields:
  code, cite (how it is cited), name, category, kind (act / rules / handbook), court, jurisdiction,
  numbering (sections / orders / chapters / rules / paras), ocr (auto / always / never), covers
  (which of a court's main rule books this is), aliases.
"""

SC = "Supreme Court of India"
DISTRICT = "District courts"
