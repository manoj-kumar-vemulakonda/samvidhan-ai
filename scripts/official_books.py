CAT_SC = "Court rules - Supreme Court"
CAT_HC = "Court rules - High Courts"
CAT_DIST = "District courts, Gram Nyayalayas and court fees"


def central(code, title, cite, category, aliases=(), **extra):
    """A central Act from India Code (found by its exact title)."""
    year = int(title[-4:]) if title[-4:].isdigit() else 0
    name = title[4:] if title.startswith("The ") else title
    return {"code": code, "indiacode": title, "cite": cite, "name": name, "short": cite, "year": year,
            "category": category, "kind": "act", "numbering": "sections", "bold": True, "ocr": "never",
            "aliases": [name.lower(), name.lower().rsplit(",", 1)[0], cite.lower(), *aliases], **extra}


def state_act(code, uuid, name, cite, state, court, category=CAT_DIST, aliases=(), **extra):
    year = int(name[-4:]) if name[-4:].isdigit() else 0
    return {"code": code, "uuid": uuid, "cite": cite, "name": name, "short": cite, "year": year, "category": category,
            "kind": "act", "numbering": "sections", "ocr": "auto", "court": court, "jurisdiction": state,
            "state": state, "aliases": [name.lower(), cite.lower(), *aliases], **extra}


def rules(code, name, cite, court, jurisdiction, category=CAT_HC, url=None, uuid=None, numbering="rules", covers=(),
          aliases=(), **extra):
    year = next((int(t) for t in reversed(name.replace(",", " ").split()) if t.isdigit() and len(t) == 4), 0)
    book = {"code": code, "cite": cite, "name": name, "short": cite, "year": year, "category": category, "kind": "rules",
            "numbering": numbering, "ocr": "auto", "court": court, "jurisdiction": jurisdiction, "covers": list(covers),
            "aliases": [name.lower(), cite.lower(), *aliases], **extra}
    if url:
        book["url"] = url
    if uuid:
        book["uuid"] = uuid
        book["state"] = jurisdiction if jurisdiction != "Central" else "CENTRAL"
    return book


